const DICTIONARIES: Record<LangCode, Dictionary> = {
  en,
  hi,
  bn,
  id,
  ar,
  vi,
  ur,
  es,
  pt,
  ru,
  th,
};

function normalizeLang(raw?: string | null): LangCode {
  const code = String(raw || 'en').trim().toLowerCase();
  if (code in DICTIONARIES) return code as LangCode;
  return 'en';
}

interface I18nContextValue {
  lang: LangCode;
  dir: 'ltr' | 'rtl';
  setLang: (next: string) => void;
  t: (key: TranslationKey, vars?: Record<string, string | number>) => string;
}

const I18nContext = createContext<I18nContextValue>({
  lang: 'en',
  dir: 'ltr',
  setLang: () => {},
  t: (key) => en[key] || key,
});

export const I18nProvider: React.FC<{ children: React.ReactNode }> = ({ children }) => {
  const [lang, setLangState] = useState<LangCode>(() => {
    try {
      return normalizeLang(localStorage.getItem('kakarot_lang'));
    } catch {
      return 'en';
    }
  });

  const activeMeta = useMemo(
    () => LANGUAGES.find((l) => l.code === lang) || LANGUAGES[0],
    [lang]
  );
  const dir: 'ltr' | 'rtl' = activeMeta.dir === 'rtl' ? 'rtl' : 'ltr';

  useEffect(() => {
    document.documentElement.lang = lang;
    document.documentElement.dir = dir;
    try {
      localStorage.setItem('kakarot_lang', lang);
    } catch {
      // ignore storage errors
    }
  }, [lang, dir]);

  const setLang = useCallback((next: string) => {
    setLangState(normalizeLang(next));
  }, []);

  const t = useCallback(
    (key: TranslationKey, vars?: Record<string, string | number>): string => {
      const dict = DICTIONARIES[lang] || en;
      let text = dict[key] || en[key] || String(key);
      if (vars) {
        for (const [k, v] of Object.entries(vars)) {
          text = text.replace(new RegExp(`\\{${k}\\}`, 'g'), String(v));
        }
      }
      return text;
    },
    [lang]
  );

  const value = useMemo(() => ({ lang, dir, setLang, t }), [lang, dir, setLang, t]);

  return <I18nContext.Provider value={value}>{children}</I18nContext.Provider>;
};

export function useI18n(): I18nContextValue {
  return useContext(I18nContext);
}
